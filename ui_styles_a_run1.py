def win(style, c0, c1):
    """Only the columns c0..c1 of the whole word, so a word can be shared out over parts that stand side by side."""
    def cut(ink, base):
        art, b = style(ink, base)
        out = art[:, c0:c1]
        if out.shape[1] == 0:
            out = np.zeros((art.shape[0], 1), np.uint8)
        return out, b
    return cut



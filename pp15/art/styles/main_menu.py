def banner(style, h, mx):
    """The word on a card piece: at least h rows high, mx clear columns each side. In these palettes index 0 is a colour
    (brown), so the clear pixels are part of the card."""
    def cut(ink, base):
        art, b = style(ink, base)
        H, W = art.shape
        oh = max(h, H)
        y = (oh - H) // 2
        out = np.zeros((oh, W + 2 * mx), np.uint8)
        out[y:y + H, mx:mx + W] = art
        return out, b + y
    return cut


def blank(w, h):
    """A plain card piece w x h (index 0): where a Japanese word is dropped, the card keeps its length."""
    def cut(ink, base):
        return np.zeros((h, w), np.uint8), 0
    return cut



"""Styles for the main menu and system screens: the versus menu, sound mode selection, the title screen, and the playoff and stage cards.

A style is a recipe that tells the lettering tool (pp15/art/typeset.py) how to draw an English label on a sprite sheet:
font, size, colours, outline, shadow.

Used by these spec files (specs/<name>.json, one per sprite file, each label names a style): dem_open, vs, sd_mode, title.
"""
